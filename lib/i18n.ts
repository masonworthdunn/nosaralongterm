export function areaLabel(area: string, lang: Language) {
  if (area === "Other") return lang === "es" ? "Otra" : "Other";
  return area;
}

export function timeAgoLabel(lang: Language, dateStr: string) {
  const diffMs = Date.now() - new Date(dateStr).getTime();
  const diffMin = Math.floor(diffMs / 60000);
  const diffHr = Math.floor(diffMin / 60);
  const diffDay = Math.floor(diffHr / 24);

  if (lang === "es") {
    if (diffDay >= 1) return `Publicado hace ${diffDay}d`;
    if (diffHr >= 1) return `Publicado hace ${diffHr}h`;
    if (diffMin >= 1) return `Publicado hace ${diffMin}m`;
    return "Publicado justo ahora";
  }

  if (diffDay >= 1) return `Posted ${diffDay}d ago`;
  if (diffHr >= 1) return `Posted ${diffHr}h ago`;
  if (diffMin >= 1) return `Posted ${diffMin}m ago`;
  return "Posted just now";
}
